const fs = require('fs');
const base = 'spanvision-pdf-workspace/open-pdf-studio/';
const file = base+'js/solid/data/nen1414Library.js';
let src = fs.readFileSync(file,'utf8');
const start = src.indexOf('const NAMES = {');
const end = src.indexOf('};',start)+2;
const names = {};
for(const m of src.slice(start,end).matchAll(/'([^']+)':\s*("(?:[^"\\]|\\.)*")/g)) names[m[1]]=JSON.parse(m[2]);
if(Object.keys(names).length < 95) throw new Error('Incomplete NEN catalog');
fs.writeFileSync(base+'js/solid/data/nen1414Names.js', '// Shared English display names. Symbol IDs remain the stable interchange keys.\nexport const NEN_NAMES = Object.freeze('+JSON.stringify(names,null,2)+');\n');
src = src.slice(0,start)+"const NAMES = NEN_NAMES;"+src.slice(end);
fs.writeFileSync(file,"import { NEN_NAMES } from './nen1414Names.js';\n"+src);
const mapping = base+'js/solid/data/nenIfcMap.js';
let map = fs.readFileSync(mapping,'utf8');
map = "import { NEN_NAMES } from './nen1414Names.js';\n"+map;
const at = map.indexOf('// Toegestane IFC4-entiteiten');
map = map.slice(0,at)+`// Preserve legacy PDF stamp names while sharing the current English catalog.\nfor (const [id, entry] of Object.entries(NEN_IFC_MAP)) {\n  entry.legacyName = entry.name;\n  entry.name = NEN_NAMES[id] || entry.name;\n}\n\n`+map.slice(at);
map = map.replace('if (!m.has(entry.name)) m.set(entry.name, id);', 'if (!m.has(entry.name)) m.set(entry.name, id);\n    if (!m.has(entry.legacyName)) m.set(entry.legacyName, id);');
fs.writeFileSync(mapping,map);
const test = base+'scripts/test-nen-ifc-map.mjs';
let t = fs.readFileSync(test,'utf8');
const from = t.indexOf('const __dirname =');
const to = t.indexOf("test('bibliotheek geparsed",from);
t=t.slice(0,from)+"import { NEN_NAMES as LIB_NAMES } from '../js/solid/data/nen1414Names.js';\n\n"+t.slice(to);
fs.writeFileSync(test,t);
