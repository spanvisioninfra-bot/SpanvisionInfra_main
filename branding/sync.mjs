function modulePalette(module) {
  const file=module.id==='calc'?'calc-workspace/src/styles/themes.css':module.id==='pdf'?'spanvision-pdf-workspace/open-pdf-studio/styles/themes.css':module.id==='cad2d'?'spanvision-2d-cad-workspace/src/styles/web.css':'ifc-view/apps/desktop/src/styles/global.css';
  const source=fs.readFileSync(path.join(root,file),'utf8');
  const start=module.id==='ifc'?0:source.lastIndexOf('/* Spanvision Mono:');
  const block=module.id==='ifc'?source.slice(0,source.indexOf('}')+1):module.id==='cad2d'?source.slice(start,source.indexOf('}',source.indexOf('[data-theme=',start))+1):source.slice(start);
  const original={'#000000':'page','#121212':'surface','#1B1B1B':'canvas','#202020':'raised','#FFFFFF':'text','#EEEEEE':'text-soft','#999999':'muted'};
  const tokens=[];
  for(const match of block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    let value=match[2].trim();let hex=value.toUpperCase();
    if(/^#[0-9A-F]{3}$/.test(hex))hex='#'+hex.slice(1).split('').map(c=>c+c).join('');
    if(original[hex])value=`var(--sv-${original[hex]})`;
    if(/focus/.test(match[1]))value='var(--sv-focus)';
    if(/border$/.test(match[1])&&/^rgba/.test(value))value='var(--sv-border)';
    if(value!==match[2].trim())tokens.push(`  ${match[1]}: ${value};`);
  }
  return css+`\n[data-theme="${brand.theme}"] {\n${tokens.join('\n')}\n}\n`;
}
