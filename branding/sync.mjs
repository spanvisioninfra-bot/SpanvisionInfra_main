const checking = process.argv.includes('--check');
const moduleFilter = process.argv.find(arg=>arg.startsWith('--modules='))?.slice('--modules='.length).split(',');
const selectedModules = brand.modules.filter(module=>!moduleFilter||moduleFilter.includes(module.id));
const errors = [];
function emit(file, content) {
  if (checking) {
    if (!fs.existsSync(path.join(root,file)) || fs.readFileSync(path.join(root,file),'utf8') !== content) errors.push(file);
  } else write(file,content);
}
const json = value => JSON.stringify(value,null,2)+'\n';
function updateJson(file, transform) {
  const value = JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
  transform(value);
  emit(file,json(value));
}
function syncPresentation(module, old) {
  const before=old.productName||old.product;
  const oldOrganization=old.organizationName||old.organization;
  const replacements=[];
  if(before&&before.length>8&&before!==displayName(module))replacements.push([before,displayName(module)]);
  const organization=module.organization||brand.organization;
  if(oldOrganization&&oldOrganization!==organization)replacements.push([oldOrganization,organization]);
  if(organization!=='Spanvision infra')replacements.push(['Spanvision infra',organization]);
  if(!replacements.length)return;
  const dirs=module.id==='cad'?['src','site','locales','packaging','web']:module.id==='ifc'?['apps/desktop/src','apps/desktop/index.html']:module.id==='frame'?['ui/src','ui/index.html']:module.id==='calculation'?['packages/desktop/src','packages/web/src','packages/web/index.html']:module.id==='stl'?['web']:module.frontendDirectory?[`${module.frontendDirectory}/src`,`${module.frontendDirectory}/public`,`${module.frontendDirectory}/index.html`]:['src','js','preview','public','index.html'];
  for(const dir of dirs)for(const file of presentationFiles(path.join(module.directory,dir))) {
    if(!/\.(tsx?|jsx?|json|rs|ftl|html|xml|desktop|plist|wxs)$/.test(file)||/\.test\.|[\\/]test[\\/]/.test(file))continue;
    let content=fs.readFileSync(file,'utf8');for(const [a,b] of replacements)content=content.replaceAll(a,b);
    emit(path.relative(root,file),content);
  }
}
function presentationFiles(relative) {
  const absolute=path.join(root,relative);
  return fs.existsSync(absolute)&&fs.statSync(absolute).isFile()?[absolute]:files(relative);
}
