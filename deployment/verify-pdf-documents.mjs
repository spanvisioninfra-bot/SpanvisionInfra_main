import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import pdfLib from '../suite-hub/node_modules/pdf-lib/cjs/index.js';

const out = path.resolve('qa/readiness/pdf-documents');
await fs.mkdir(out, {recursive:true});
const pdf = await pdfLib.PDFDocument.create();
pdf.addPage([400,300]).drawText('Spanvision PDF round trip', {x:30,y:240,size:14});
const rotated = pdf.addPage([400,300]);
rotated.drawText('Rotated second page', {x:30,y:240,size:14});
rotated.setRotation(pdfLib.degrees(90));
const source = Buffer.from(await pdf.save());
await fs.writeFile(path.join(out,'source.pdf'),source);
const browser = await chromium.launch({channel:'msedge',headless:true});
const checks=[], errors=[];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  page.on('pageerror',error=>errors.push(error.message));
  const origin = process.env.PDF_TEST_URL || 'http://127.0.0.1:3084/';
  await page.goto(origin, {waitUntil:'domcontentloaded',timeout:60000});
  const selecting=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'Open PDF',exact:true}).click();
  await (await selecting).setFiles({name:'source.pdf',mimeType:'application/pdf',buffer:source});
  await page.locator('#pdf-canvas').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#pdf-canvas')?.width>0);
  const canvas=page.locator('#annotation-canvas');
  const painted=await page.locator('#pdf-canvas').evaluate(c=>{
    const data=c.getContext('2d').getImageData(0,0,c.width,c.height).data;
    return data.some((value,index)=>index%4===3&&value>0);
  });
  assert.equal(painted,true);
  checks.push('Actual two-page PDF opens and paints its page canvas');
  await page.getByRole('button',{name:'Drawing',exact:true}).click();
  await page.locator('#dr-rect').click();
  const box=await canvas.boundingBox();
  assert.ok(box?.width>250&&box.height>180);
  const start={x:box.x+box.width*0.20,y:box.y+box.height*0.35};
  const end={x:box.x+box.width*0.55,y:box.y+box.height*0.65};
  await page.mouse.move(start.x,start.y); await page.mouse.down();
  await page.mouse.move(end.x,end.y,{steps:8}); await page.mouse.up();
  await page.keyboard.press('Escape');
  for(const mode of ['light','dark']) {
    await page.getByLabel('Color mode',{exact:true}).selectOption(mode);
    await page.waitForFunction(mode=>document.documentElement.dataset.svMode===mode,mode);
    const size=await canvas.evaluate(c=>({width:c.width,height:c.height}));
    assert.ok(size.width>0&&size.height>0);
    await page.screenshot({path:path.join(out,`annotation-${mode}.png`)});
  }
  checks.push('Rectangle drawn through mouse input; page and annotation canvases remain sized in both themes');
  await page.evaluate(()=>{window.showSaveFilePicker=undefined;});
  const downloading=page.waitForEvent('download');
  await page.keyboard.press('Control+Shift+s');
  const file=await downloading; assert.equal(await file.failure(),null);
  const saved=path.join(out,'annotated.pdf'); await file.saveAs(saved);
  const result=await pdfLib.PDFDocument.load(await fs.readFile(saved));
  assert.equal(result.getPageCount(),2);
  assert.equal(result.getPage(1).getRotation().angle,90);
  const annotations=result.getPage(0).node.lookup(pdfLib.PDFName.of('Annots'),pdfLib.PDFArray);
  assert.equal(annotations.size(),1);
  const annotation=annotations.lookup(0,pdfLib.PDFDict);
  assert.equal(annotation.lookup(pdfLib.PDFName.of('Subtype')).toString(),'/Square');
  const rect=annotation.lookup(pdfLib.PDFName.of('Rect'),pdfLib.PDFArray).asArray().map(n=>n.asNumber());
  assert.ok(rect[0]>=0&&rect[1]>=0&&rect[2]>rect[0]&&rect[3]>rect[1]&&rect[2]<=400&&rect[3]<=300);
  assert.ok(annotation.has(pdfLib.PDFName.of('AP')),'Saved annotation has an actual PDF appearance');
  checks.push('Save As downloads a PDF retaining both pages, 90-degree page rotation and a bounded rectangle appearance');
  const reopened=await context.newPage(); reopened.on('pageerror',error=>errors.push(error.message));
  await reopened.goto(origin, {waitUntil:'domcontentloaded',timeout:60000});
  const opening=reopened.waitForEvent('filechooser');
  await reopened.getByRole('button',{name:'Open PDF',exact:true}).click();
  await (await opening).setFiles(saved);
  await reopened.waitForFunction(()=>document.querySelector('#pdf-canvas')?.width>0);
  await reopened.getByText('1 (1 total)',{exact:true}).waitFor();
  checks.push('Downloaded annotated PDF reopens with its actual annotation');
  await reopened.bringToFront();
  await reopened.locator('#annotation-canvas').click({position:{x:10,y:10}});
  const anotherOpening = reopened.waitForEvent('filechooser');
  await reopened.keyboard.press('Control+o');
  await (await anotherOpening).setFiles({name:'other.pdf',mimeType:'application/pdf',buffer:source});
  await reopened.locator('.document-tab').filter({hasText:'other.pdf'}).waitFor();
  await reopened.waitForFunction(()=>document.querySelector('#pdf-canvas')?.width>0);
  await reopened.locator('.document-tab').filter({hasText:'annotated.pdf'}).click();
  await reopened.getByText('1 (1 total)',{exact:true}).waitFor();
  const beforeFailure = await reopened.locator('.document-tab').count();
  await reopened.locator('#annotation-canvas').click({position:{x:10,y:10}});
  const cancelling = reopened.waitForEvent('filechooser');
  await reopened.keyboard.press('Control+o');
  const cancelled = await cancelling;
  await cancelled.element().evaluate(input => input.dispatchEvent(new Event('cancel')));
  assert.equal(await reopened.locator('.document-tab').count(),beforeFailure);
  await reopened.getByText('1 (1 total)',{exact:true}).waitFor();
  checks.push('Cancelling the browser file picker preserves the open annotated document');
  await reopened.locator('#annotation-canvas').click({position:{x:10,y:10}});
  const invalidOpening = reopened.waitForEvent('filechooser');
  await reopened.keyboard.press('Control+o');
  await (await invalidOpening).setFiles({name:'broken.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7\nbroken')});
  await reopened.getByText(/Failed to load PDF:/).waitFor();
  await reopened.getByRole('button',{name:'OK',exact:true}).click();
  await reopened.locator('.loading-overlay.visible').waitFor({state:'hidden'});
  assert.equal(await reopened.locator('.document-tab').count(),beforeFailure,'A failed import must not leave an empty document tab');
  await reopened.getByText('1 (1 total)',{exact:true}).waitFor();
  await reopened.locator('#pdf-canvas').waitFor({state:'visible'});
  checks.push('Malformed PDF reports its failure and restores the active annotated document, including a non-adjacent tab');
  const fresh = await context.newPage(); fresh.on('pageerror',error=>errors.push(error.message));
  await fresh.goto(origin, {waitUntil:'domcontentloaded',timeout:60000});
  const firstInvalid = fresh.waitForEvent('filechooser');
  await fresh.getByRole('button',{name:'Open PDF',exact:true}).click();
  await (await firstInvalid).setFiles({name:'bad-first.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7\nbroken')});
  await fresh.getByText(/Failed to load PDF:/).waitFor();
  await fresh.getByRole('button',{name:'OK',exact:true}).click();
  await fresh.locator('.loading-overlay.visible').waitFor({state:'hidden'});
  assert.equal(await fresh.locator('.document-tab').count(),0);
  const retry = fresh.waitForEvent('filechooser');
  await fresh.getByRole('button',{name:'Open PDF',exact:true}).click();
  await (await retry).setFiles(saved);
  await fresh.getByText('1 (1 total)',{exact:true}).waitFor();
  checks.push('A malformed first import leaves no failed tab and a valid retry opens the actual saved annotation');
  assert.deepEqual(errors,[]);
  await context.close();
  await fs.writeFile(path.join(out,'verification.json'),JSON.stringify({passed:true,checkedAt:new Date().toISOString(),checks,errors},null,2));
  console.log(JSON.stringify({passed:true,checks},null,2));
} catch(error) {
  console.error('PDF browser verification failed:',error);
  await fs.writeFile(path.join(out,'verification.json'),JSON.stringify({passed:false,checkedAt:new Date().toISOString(),checks,errors,error:String(error)},null,2));
  throw error;
} finally { await browser.close(); }
